vim.api.nvim_create_autocmd('VimEnter',{once=true,callback=function() vim.defer_fn(function()
  local ok,err=xpcall(function()
    local config=dofile(vim.fn.fnamemodify(debug.getinfo(1, 'S').source:sub(2), ':p:h:h') .. '/after/lsp/astro.lua')
    local root=vim.fn.tempname()
    vim.fn.mkdir(root..'/node_modules/typescript/lib','p')
    vim.fn.writefile({'// test project SDK marker'},root..'/node_modules/typescript/lib/typescript.js')
    local cfg={root_dir=root,init_options={typescript={}}}
    config.before_init({},cfg)
    assert(cfg.init_options.typescript.tsdk==root..'/node_modules/typescript/lib','project SDK did not win')
    local explicit=vim.fn.tempname();vim.fn.mkdir(explicit,'p');vim.fn.writefile({'// explicit SDK'},explicit..'/typescript.js')
    cfg.init_options.typescript.tsdk=explicit;config.before_init({},cfg)
    assert(cfg.init_options.typescript.tsdk==explicit,'explicit SDK override was replaced')
    local loose=vim.fn.tempname();vim.fn.mkdir(loose,'p')
    cfg={root_dir=loose,init_options={typescript={}}};config.before_init({},cfg)
    assert(cfg.init_options.typescript.tsdk and vim.uv.fs_stat(cfg.init_options.typescript.tsdk..'/typescript.js'),'loose-file fallback unavailable')
    print('PASS Astro project SDK, explicit SDK and default fallback selection')
  end,debug.traceback)
  if not ok then io.stderr:write(err..'\n');vim.cmd('cquit 1') end
  vim.cmd('qa!')
end,100) end})
